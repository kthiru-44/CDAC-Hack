"""
Target Code Generator for NVIDIA CUDA-Q >= 0.8.0.

Emits clean, idiomatic Python code with CUDA-Q kernels:
@cudaq.kernel, cudaq.qvector, controlled gate syntax (.ctrl), and standalone execution.
"""

from __future__ import annotations
import math
from typing import Tuple, Dict, Any
from qnvkit.ir import CircuitIR, Op
from qnvkit.report import TranspilerReport, TranspileResult

TARGET_VERSION = "cudaq>=0.8.0"


def generate_cudaq_code(circuit: CircuitIR) -> TranspileResult:
    report = TranspilerReport(
        target="cudaq",
        target_version=TARGET_VERSION
    )

    lines = []
    lines.append('"""')
    lines.append(f'Generated by qnvkit OpenQASM 3.0 Transpiler')
    lines.append(f'Target Framework: NVIDIA CUDA-Q ({TARGET_VERSION})')
    lines.append('"""')
    lines.append("import numpy as np")
    lines.append("try:")
    lines.append("    import cudaq")
    lines.append("except ImportError:")
    lines.append("    cudaq = None\n")

    circuit_name = circuit.name.replace("-", "_")
    lines.append("@cudaq.kernel if cudaq is not None else lambda fn: fn")
    lines.append(f"def {circuit_name}():")
    indent = "    "

    # 1. Allocate qubits
    lines.append(f"{indent}# Qubit allocations")
    for r in circuit.qregs:
        report.qubit_mapping[r.name] = r.size
        lines.append(f"{indent}{r.name} = cudaq.qvector({r.size})")

    for c in circuit.cregs:
        report.clbit_mapping[c.name] = c.size

    lines.append("")

    # 2. Operations
    gate_counts = {}
    for op in circuit.ops:
        gate_counts[op.name] = gate_counts.get(op.name, 0) + 1
        op_code = _translate_cudaq_op(op, circuit, report)
        if op_code:
            if op.condition:
                if isinstance(op.condition, tuple):
                    cname, cval = op.condition
                    cond_target = cname
                    val = cval
                else:
                    c = op.condition
                    cond_target = f"{c.register}_{c.index}" if getattr(c, "index", None) is not None else c.register
                    val = c.value
                lines.append(f"{indent}if {cond_target} == {val}:")
                lines.append(f"{indent}    {op_code}")
            else:
                lines.append(f"{indent}{op_code}")

    lines.append("")

    # 3. Runnable __main__
    lines.append("if __name__ == '__main__':")
    lines.append("    if cudaq is None:")
    lines.append("        print('CUDA-Q package is not installed on this host.')")
    lines.append("        print('The generated kernel syntax is valid for CUDA-Q 0.8+ environments.')")
    lines.append("    else:")
    lines.append(f"        print('=== Executing CUDA-Q Kernel: {circuit_name} ===')")
    lines.append("        try:")
    lines.append(f"            counts = cudaq.sample({circuit_name}, shots_count=1024)")
    lines.append("            print('\\nMeasurement results (1024 shots):')")
    lines.append("            print(counts)")
    lines.append("        except Exception as e:")
    lines.append("            print(f'CUDA-Q simulation note: {e}')")

    code_str = "\n".join(lines) + "\n"
    report.metrics = {
        "num_qubits": circuit.num_qubits,
        "num_clbits": circuit.num_clbits,
        "total_ops": len(circuit.ops),
        "gate_counts": gate_counts
    }

    return TranspileResult(target="cudaq", code=code_str, report=report)


def _translate_cudaq_op(op: Op, circuit: CircuitIR, report: TranspilerReport) -> str:
    name = op.name.lower()
    q_map = circuit.get_qubit_reg_map()
    qubits = []
    for q in op.qubits:
        if isinstance(q, int):
            r_name, r_idx = q_map.get(q, ('q', q))
            qubits.append(f"{r_name}[{r_idx}]")
        else:
            qubits.append(f"{q.register}[{q.index}]")

    c_map = circuit.get_clbit_reg_map()
    clbits = []
    for c in op.clbits:
        if isinstance(c, int):
            cr_name, cr_idx = c_map.get(c, ('c', c))
            clbits.append(f"{cr_name}_{cr_idx}")
        else:
            clbits.append(f"{c.register}_{c.index}")

    params = [f"{p:.12g}" for p in op.params]

    # Non-unitary operations
    if name == "barrier":
        return f"# Barrier on {', '.join(qubits)}"
    if name == "reset":
        return f"cudaq.reset({qubits[0]})"
    if name == "measure":
        if len(qubits) == 1 and len(clbits) == 1:
            q = qubits[0]
            var = clbits[0]
            return f"{var} = cudaq.mz({q})"
        report.add_warning("Measurement has invalid arity in CUDA-Q generator")
        return f"# Unsupported measure: {op}"

    # Single-Qubit Standard Gates
    if name == "id":
        return f"# Identity on {qubits[0]}"
    if name == "x":
        return f"cudaq.x({qubits[0]})"
    if name == "y":
        return f"cudaq.y({qubits[0]})"
    if name == "z":
        return f"cudaq.z({qubits[0]})"
    if name == "h":
        return f"cudaq.h({qubits[0]})"
    if name == "s":
        return f"cudaq.s({qubits[0]})"
    if name == "sdg":
        return f"cudaq.rz(-np.pi/2, {qubits[0]})"
    if name == "t":
        return f"cudaq.t({qubits[0]})"
    if name == "tdg":
        return f"cudaq.rz(-np.pi/4, {qubits[0]})"
    if name in ("p", "phase", "u1", "rz"):
        return f"cudaq.rz({params[0]}, {qubits[0]})"
    if name == "rx":
        return f"cudaq.rx({params[0]}, {qubits[0]})"
    if name == "ry":
        return f"cudaq.ry({params[0]}, {qubits[0]})"
    if name in ("u", "u3"):
        return f"cudaq.rz({params[2]}, {qubits[0]}); cudaq.ry({params[0]}, {qubits[0]}); cudaq.rz({params[1]}, {qubits[0]})"

    # Two-Qubit / Controlled Gates
    if name in ("cx", "cnot"):
        return f"cudaq.x.ctrl({qubits[0]}, {qubits[1]})"
    if name == "cy":
        return f"cudaq.y.ctrl({qubits[0]}, {qubits[1]})"
    if name == "cz":
        return f"cudaq.z.ctrl({qubits[0]}, {qubits[1]})"
    if name == "ch":
        return f"cudaq.h.ctrl({qubits[0]}, {qubits[1]})"
    if name == "swap":
        return f"cudaq.swap({qubits[0]}, {qubits[1]})"
    if name in ("cp", "cphase", "cu1", "crz"):
        return f"cudaq.rz.ctrl({params[0]}, {qubits[0]}, {qubits[1]})"
    if name == "crx":
        return f"cudaq.rx.ctrl({params[0]}, {qubits[0]}, {qubits[1]})"
    if name == "cry":
        return f"cudaq.ry.ctrl({params[0]}, {qubits[0]}, {qubits[1]})"

    # Multi-Qubit Gates
    if name in ("ccx", "toffoli"):
        return f"cudaq.x.ctrl([{qubits[0]}, {qubits[1]}], {qubits[2]})"
    if name in ("c3x", "c4x", "c5x"):
        controls = ", ".join(qubits[:-1])
        target = qubits[-1]
        return f"cudaq.x.ctrl([{controls}], {target})"

    report.add_unsupported(f"Gate '{name}' not natively supported in CUDA-Q generator", op.line, op.col)
    return f"# Unsupported gate: {op}"
