"""
Target Code Generator for Cirq >= 1.4.

Qubits are NamedQubit('<reg>_<i>'), measurement keys are per bit ('<creg>_<i>'). Classical
conditions use ``with_classical_controls(sympy.Eq(Symbol(key), bit))``, one term per bit.
Barriers have no Cirq equivalent and are omitted (recorded in the report).
"""

from __future__ import annotations
from typing import Dict, List, Set
from qnvkit.ir import CircuitIR, Op
from qnvkit.report import TranspilerReport, TranspileResult
from qnvkit.transpile._common import (
    prepare_ops, py_name, fmt_param, qubit_names, clbit_keys, set_metrics, condition_terms,
)

TARGET_VERSION = "cirq>=1.4.0"

NATIVE = {
    "id", "x", "y", "z", "h", "s", "sdg", "t", "tdg", "sx", "sxdg", "p", "u1", "rx", "ry", "rz",
    "cx", "cy", "cz", "ch", "swap", "cs", "csdg", "ct", "ctdg", "cp", "cu1", "crx", "cry", "crz",
    "ccx", "cswap", "c3x", "c4x", "c5x",
}


def generate_cirq_code(circuit: CircuitIR) -> TranspileResult:
    report = TranspilerReport(target="cirq", target_version=TARGET_VERSION)
    set_metrics(report, circuit)
    qn = qubit_names(circuit)
    keys = clbit_keys(circuit)
    ops = prepare_ops(circuit, NATIVE, {"rz", "ry", "p", "cx"}, report, "Cirq")
    ind = "    "

    lines = [
        '"""',
        "Generated by qnvkit OpenQASM 3.0 Transpiler",
        f"Target Framework: Cirq ({TARGET_VERSION})",
        '"""',
        "import numpy as np",
        "import sympy",
        "import cirq",
        "",
        "",
        "def build_circuit() -> cirq.Circuit:",
        f"{ind}circuit = cirq.Circuit()",
    ]
    for r in circuit.qregs:
        lines.append(f"{ind}{py_name(r.name)} = [cirq.NamedQubit('{r.name}_%d' % i) for i in range({r.size})]")
    lines.append("")

    measured: Set[int] = set()
    has_measure = False
    for op in ops:
        if op.name == "barrier":
            report.add_note("barrier omitted: Cirq has no barrier operation")
            continue
        expr = _translate(op, qn, keys, report)
        if expr is None:
            continue
        if op.name == "measure":
            if op.condition:
                report.add_unsupported("Conditional measurement is not supported by the Cirq generator", op.line, op.col)
                continue
            measured.add(op.clbits[0])
            has_measure = True
        terms = []
        never = False
        if op.condition:
            for bit, req in condition_terms(circuit, op):
                if bit in measured:
                    terms.append(f"sympy.Eq(sympy.Symbol('{keys[bit]}'), {req})")
                elif req == 1:
                    never = True  # an unmeasured bit is 0 and can never be 1
            if never:
                report.add_warning("Condition can never hold (bit tested for 1 before any measurement); operation skipped")
                continue
        if terms:
            expr = f"({expr}).with_classical_controls({', '.join(terms)})"
        lines.append(f"{ind}circuit.append({expr})")

    key_list = [keys[i] if i in measured else None for i in range(circuit.num_clbits)]
    lines += [
        "",
        f"{ind}return circuit",
        "",
        "",
        "# Classical bit i (flat order) -> measurement key; None if never measured.",
        f"CLBIT_KEYS = {key_list!r}",
        "SHOTS = 1024",
        "",
        "",
        "if __name__ == '__main__':",
        "    circuit = build_circuit()",
        "    print('=== Generated Cirq Circuit ===')",
        "    print(circuit)",
        "    try:",
    ]
    if has_measure:
        lines += [
            "        result = cirq.Simulator().run(circuit, repetitions=SHOTS)",
            "        counts = {}",
            "        for s in range(SHOTS):",
            "            # bitstring over all classical bits, classical bit 0 right-most",
            "            bits = ''.join(str(int(result.records[k][s, -1, 0])) if k else '0' for k in reversed(CLBIT_KEYS))",
            "            counts[bits] = counts.get(bits, 0) + 1",
            "        print(f'\\nCounts ({SHOTS} shots, classical bit 0 right-most):')",
            "        print(dict(sorted(counts.items())))",
        ]
    else:
        order = ", ".join(qn[i] for i in range(circuit.num_qubits))
        lines += [
            f"        qubit_order = [{order}]",
            "        result = cirq.Simulator().simulate(circuit, qubit_order=qubit_order)",
            "        print('\\nFinal state vector (cirq order: first qubit most significant):')",
            "        print(np.round(result.final_state_vector, 4))",
        ]
    lines += ["    except Exception as e:", "        print(f'Simulation note: {e}')"]
    return TranspileResult(target="cirq", code="\n".join(lines) + "\n", report=report)


def _translate(op: Op, qn: Dict[int, str], keys: Dict[int, str], report: TranspilerReport):
    name = op.name
    qs = [qn[q] for q in op.qubits]
    ps = [fmt_param(p) for p in op.params]
    if name == "reset":
        return f"cirq.reset({qs[0]})"
    if name == "measure":
        return f"cirq.measure({qs[0]}, key='{keys[op.clbits[0]]}')"
    simple = {"id": "cirq.I({0})", "x": "cirq.X({0})", "y": "cirq.Y({0})", "z": "cirq.Z({0})", "h": "cirq.H({0})",
              "s": "cirq.S({0})", "sdg": "(cirq.S({0})**-1)", "t": "cirq.T({0})", "tdg": "(cirq.T({0})**-1)",
              "sx": "(cirq.X({0})**0.5)", "sxdg": "(cirq.X({0})**-0.5)"}
    if name in simple:
        return simple[name].format(*qs)
    if name in ("p", "u1"):
        return f"cirq.ZPowGate(exponent={ps[0]} / np.pi)({qs[0]})"
    if name in ("rx", "ry", "rz"):
        return f"cirq.{name}({ps[0]})({qs[0]})"
    two = {"cx": "cirq.CNOT({0}, {1})", "cz": "cirq.CZ({0}, {1})", "swap": "cirq.SWAP({0}, {1})",
           "cy": "cirq.Y({1}).controlled_by({0})", "ch": "cirq.H({1}).controlled_by({0})",
           "cs": "cirq.S({1}).controlled_by({0})", "csdg": "(cirq.S({1})**-1).controlled_by({0})",
           "ct": "cirq.T({1}).controlled_by({0})", "ctdg": "(cirq.T({1})**-1).controlled_by({0})",
           "ccx": "cirq.CCNOT({0}, {1}, {2})", "cswap": "cirq.CSWAP({0}, {1}, {2})"}
    if name in two:
        return two[name].format(*qs)
    if name in ("cp", "cu1"):
        return f"cirq.CZPowGate(exponent={ps[0]} / np.pi)({qs[0]}, {qs[1]})"
    if name in ("crx", "cry", "crz"):
        return f"cirq.{name[1:]}({ps[0]})({qs[1]}).controlled_by({qs[0]})"
    if name in ("c3x", "c4x", "c5x"):
        return f"cirq.X({qs[-1]}).controlled_by({', '.join(qs[:-1])})"
    report.add_unsupported(f"Gate '{name}' not supported by the Cirq generator", op.line, op.col)
    return None
