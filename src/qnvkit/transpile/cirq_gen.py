"""
Target Code Generator for Google Cirq >= 1.4.0.

Emits clean, idiomatic, fully runnable Python code with standard Cirq APIs:
cirq.Circuit, NamedQubit/LineQubit mapping, measurement keys, and standalone simulation.
"""

from __future__ import annotations
import math
from typing import Tuple, Dict, Any
from qnvkit.ir import CircuitIR, Op
from qnvkit.report import TranspilerReport, TranspileResult

TARGET_VERSION = "cirq>=1.4.0"


def generate_cirq_code(circuit: CircuitIR) -> TranspileResult:
    report = TranspilerReport(
        target="cirq",
        target_version=TARGET_VERSION
    )

    lines = []
    lines.append('"""')
    lines.append(f'Generated by qnvkit OpenQASM 3.0 Transpiler')
    lines.append(f'Target Framework: Cirq ({TARGET_VERSION})')
    lines.append('"""')
    lines.append("import numpy as np")
    lines.append("import cirq\n")
    lines.append("def build_circuit() -> cirq.Circuit:")
    indent = "    "
    lines.append(f"{indent}circuit = cirq.Circuit()\n")

    # 1. Qubit allocation
    lines.append(f"{indent}# Qubit allocation")
    for r in circuit.qregs:
        report.qubit_mapping[r.name] = r.size
        lines.append(f"{indent}{r.name} = [cirq.NamedQubit(f'{r.name}_{{i}}') for i in range({r.size})]")

    for c in circuit.cregs:
        report.clbit_mapping[c.name] = c.size

    lines.append("")

    # 2. Operations
    gate_counts = {}
    for op in circuit.ops:
        gate_counts[op.name] = gate_counts.get(op.name, 0) + 1
        op_code = _translate_cirq_op(op, circuit, report)
        if op_code:
            if op.condition:
                if isinstance(op.condition, tuple):
                    cname, cval = op.condition
                    key = f"'{cname}'"
                else:
                    c = op.condition
                    key = f"'{c.register}_{c.index}'" if getattr(c, "index", None) is not None else f"'{c.register}'"
                lines.append(f"{indent}circuit.append(cirq.ClassicallyControlledOperation({op_code}, conditions=[cirq.KeyCondition(cirq.MeasurementKey({key}))]))")
            else:
                lines.append(f"{indent}circuit.append({op_code})")

    lines.append(f"\n{indent}return circuit\n")

    # 3. Runnable __main__
    lines.append("if __name__ == '__main__':")
    lines.append("    circuit = build_circuit()")
    lines.append("    print('=== Generated Cirq Circuit ===')")
    lines.append("    print(circuit)")
    lines.append("    try:")
    lines.append("        sim = cirq.Simulator()")
    lines.append("        # Check if circuit contains measurements")
    lines.append("        has_meas = any(isinstance(op.gate, cirq.MeasurementGate) for op in circuit.all_operations())")
    lines.append("        if has_meas:")
    lines.append("            result = sim.run(circuit, repetitions=1024)")
    lines.append("            print('\\nMeasurement results (1024 repetitions):')")
    lines.append("            print(result.histogram(key=list(result.records.keys())[0]))")
    lines.append("        else:")
    lines.append("            result = sim.simulate(circuit)")
    lines.append("            print('\\nFinal state vector:')")
    lines.append("            print(np.round(result.final_state_vector, 4))")
    lines.append("    except Exception as e:")
    lines.append("        print(f'Simulation note: {e}')")

    code_str = "\n".join(lines) + "\n"
    report.metrics = {
        "num_qubits": circuit.num_qubits,
        "num_clbits": circuit.num_clbits,
        "total_ops": len(circuit.ops),
        "gate_counts": gate_counts
    }

    return TranspileResult(target="cirq", code=code_str, report=report)


def _translate_cirq_op(op: Op, circuit: CircuitIR, report: TranspilerReport) -> str:
    name = op.name.lower()
    q_map = circuit.get_qubit_reg_map()
    qubits = []
    for q in op.qubits:
        if isinstance(q, int):
            r_name, r_idx = q_map.get(q, ('q', q))
            qubits.append(f"{r_name}[{r_idx}]")
        else:
            qubits.append(f"{q.register}[{q.index}]")

    c_map = circuit.get_clbit_reg_map()
    clbits = []
    for c in op.clbits:
        if isinstance(c, int):
            cr_name, cr_idx = c_map.get(c, ('c', c))
            clbits.append(f"{cr_name}_{cr_idx}")
        else:
            clbits.append(f"{c.register}_{c.index}")

    params = [f"{p:.12g}" for p in op.params]

    # Non-unitary operations
    if name == "barrier":
        return f"# Barrier on {', '.join(qubits)}"
    if name == "reset":
        return f"cirq.reset({qubits[0]})"
    if name == "measure":
        if len(qubits) == 1 and len(clbits) == 1:
            q = qubits[0]
            key = clbits[0]
            return f"cirq.measure({q}, key='{key}')"
        report.add_warning("Measurement has invalid arity in Cirq generator")
        return f"# Unsupported measure: {op}"

    # Single-Qubit Standard Gates
    if name == "id":
        return f"cirq.I({qubits[0]})"
    if name == "x":
        return f"cirq.X({qubits[0]})"
    if name == "y":
        return f"cirq.Y({qubits[0]})"
    if name == "z":
        return f"cirq.Z({qubits[0]})"
    if name == "h":
        return f"cirq.H({qubits[0]})"
    if name == "s":
        return f"cirq.S({qubits[0]})"
    if name == "sdg":
        return f"cirq.S({qubits[0]})**-1"
    if name == "t":
        return f"cirq.T({qubits[0]})"
    if name == "tdg":
        return f"cirq.T({qubits[0]})**-1"
    if name == "sx":
        return f"cirq.X({qubits[0]})**0.5"
    if name == "sxdg":
        return f"cirq.X({qubits[0]})**-0.5"
    if name in ("p", "phase", "u1"):
        return f"cirq.ZPowGate(exponent={params[0]} / np.pi)({qubits[0]})"
    if name == "rx":
        return f"cirq.rx({params[0]})({qubits[0]})"
    if name == "ry":
        return f"cirq.ry({params[0]})({qubits[0]})"
    if name == "rz":
        return f"cirq.rz({params[0]})({qubits[0]})"
    if name in ("u", "u3"):
        return f"cirq.Circuit([cirq.rz({params[2]})({qubits[0]}), cirq.ry({params[0]})({qubits[0]}), cirq.rz({params[1]})({qubits[0]})]).all_operations()"
    if name == "u2":
        return f"cirq.Circuit([cirq.rz({params[1]})({qubits[0]}), cirq.ry(np.pi/2)({qubits[0]}), cirq.rz({params[0]})({qubits[0]})]).all_operations()"

    # Two-Qubit / Controlled Gates
    if name in ("cx", "cnot"):
        return f"cirq.CNOT({qubits[0]}, {qubits[1]})"
    if name == "cy":
        return f"cirq.Y({qubits[1]}).controlled_by({qubits[0]})"
    if name == "cz":
        return f"cirq.CZ({qubits[0]}, {qubits[1]})"
    if name == "ch":
        return f"cirq.H({qubits[1]}).controlled_by({qubits[0]})"
    if name == "swap":
        return f"cirq.SWAP({qubits[0]}, {qubits[1]})"
    if name == "cs":
        return f"cirq.S({qubits[1]}).controlled_by({qubits[0]})"
    if name == "csdg":
        return f"(cirq.S({qubits[1]})**-1).controlled_by({qubits[0]})"
    if name == "ct":
        return f"cirq.T({qubits[1]}).controlled_by({qubits[0]})"
    if name == "ctdg":
        return f"(cirq.T({qubits[1]})**-1).controlled_by({qubits[0]})"
    if name in ("cp", "cphase", "cu1"):
        return f"cirq.CZPowGate(exponent={params[0]} / np.pi)({qubits[0]}, {qubits[1]})"
    if name == "crx":
        return f"cirq.rx({params[0]})({qubits[1]}).controlled_by({qubits[0]})"
    if name == "cry":
        return f"cirq.ry({params[0]})({qubits[1]}).controlled_by({qubits[0]})"
    if name == "crz":
        return f"cirq.rz({params[0]})({qubits[1]}).controlled_by({qubits[0]})"

    # Multi-Qubit Gates
    if name in ("ccx", "toffoli"):
        return f"cirq.CCNOT({qubits[0]}, {qubits[1]}, {qubits[2]})"
    if name == "cswap":
        return f"cirq.CSWAP({qubits[0]}, {qubits[1]}, {qubits[2]})"
    if name in ("c3x", "c4x", "c5x"):
        controls = ", ".join(qubits[:-1])
        target = qubits[-1]
        return f"cirq.X({target}).controlled_by({controls})"

    report.add_unsupported(f"Gate '{name}' not natively supported in Cirq generator", op.line, op.col)
    return f"# Unsupported gate: {op}"
