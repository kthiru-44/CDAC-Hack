"""
Target Code Generator for Qiskit >= 1.0.0.

Emits clean, idiomatic, fully runnable Python code with modern Qiskit APIs:
QuantumCircuit, if_test blocks, exact parameter preservation, and standalone execution.
"""

from __future__ import annotations
import math
from typing import Tuple, Dict, Any
from qnvkit.ir import CircuitIR, Op
from qnvkit.report import TranspilerReport, TranspileResult

TARGET_VERSION = "qiskit>=1.0.0"


def generate_qiskit_code(circuit: Any) -> TranspileResult:
    if not isinstance(circuit, CircuitIR):
        from qnvkit.qsdk_adapter import from_qniverse
        circuit = from_qniverse(circuit)

    report = TranspilerReport(
        target="qiskit",
        target_version=TARGET_VERSION
    )

    lines = []
    lines.append('"""')
    lines.append(f'Generated by qnvkit OpenQASM 3.0 Transpiler')
    lines.append(f'Target Framework: Qiskit ({TARGET_VERSION})')
    lines.append('"""')
    lines.append("import numpy as np")
    lines.append("from qiskit import QuantumCircuit, QuantumRegister, ClassicalRegister\n")
    lines.append("def build_circuit() -> QuantumCircuit:")

    # 1. Register declarations
    indent = "    "
    reg_names_list = []
    for r in circuit.qregs:
        lines.append(f"{indent}{r.name} = QuantumRegister({r.size}, name='{r.name}')")
        reg_names_list.append(r.name)
        report.qubit_mapping[r.name] = r.size

    for c in circuit.cregs:
        lines.append(f"{indent}{c.name} = ClassicalRegister({c.size}, name='{c.name}')")
        reg_names_list.append(c.name)
        report.clbit_mapping[c.name] = c.size

    regs_arg = ", ".join(reg_names_list)
    circuit_name = circuit.name.replace("-", "_")
    lines.append(f"{indent}qc = QuantumCircuit({regs_arg}, name='{circuit_name}')\n")

    # 2. Operations
    gate_counts = {}
    for op in circuit.ops:
        gate_counts[op.name] = gate_counts.get(op.name, 0) + 1
        curr_indent = indent

        # Handle condition: with qc.if_test((creg, val)):
        if op.condition:
            if isinstance(op.condition, tuple):
                cname, cval = op.condition
                lines.append(f"{indent}with qc.if_test(({cname}, {cval})):")
            else:
                c = op.condition
                if getattr(c, "index", None) is not None:
                    lines.append(f"{indent}with qc.if_test(({c.register}[{c.index}], {c.value})):")
                else:
                    lines.append(f"{indent}with qc.if_test(({c.register}, {c.value})):")
            curr_indent = indent + "    "

        # Translate operation
        op_code = _translate_op(op, circuit, report)
        if op_code:
            lines.append(f"{curr_indent}{op_code}")

    lines.append(f"\n{indent}return qc\n")

    # 3. Runnable __main__
    lines.append("if __name__ == '__main__':")
    lines.append("    circuit = build_circuit()")
    lines.append("    print('=== Generated Qiskit Circuit ===')")
    lines.append("    print(circuit.draw(output='text'))")
    lines.append("    try:")
    lines.append("        from qiskit.quantum_info import Statevector")
    lines.append("        # Compute statevector for unitary subcircuit")
    lines.append("        sub_cir = circuit.remove_final_measurements(inplace=False)")
    lines.append("        sv = Statevector(sub_cir)")
    lines.append("        print('\\nStatevector probabilities:')")
    lines.append("        print(sv.probabilities_dict())")
    lines.append("    except Exception as e:")
    lines.append("        print(f'Simulation note: {e}')")

    code_str = "\n".join(lines) + "\n"
    report.metrics = {
        "num_qubits": circuit.num_qubits,
        "num_clbits": circuit.num_clbits,
        "total_ops": len(circuit.ops),
        "gate_counts": gate_counts
    }

    return TranspileResult(target="qiskit", code=code_str, report=report)


def _translate_op(op: Op, circuit: CircuitIR, report: TranspilerReport) -> str:
    name = op.name.lower()
    q_map = circuit.get_qubit_reg_map()
    qubits = []
    for q in op.qubits:
        if isinstance(q, int):
            r_name, r_idx = q_map.get(q, ('q', q))
            qubits.append(f"{r_name}[{r_idx}]")
        else:
            qubits.append(f"{q.register}[{q.index}]")

    c_map = circuit.get_clbit_reg_map()
    clbits = []
    for c in op.clbits:
        if isinstance(c, int):
            cr_name, cr_idx = c_map.get(c, ('c', c))
            clbits.append(f"{cr_name}[{cr_idx}]")
        else:
            clbits.append(f"{c.register}[{c.index}]")

    params = [f"{p:.12g}" for p in op.params]

    # Non-unitary operations
    if name == "barrier":
        q_args = ", ".join(qubits)
        return f"qc.barrier({q_args})"
    if name == "reset":
        return f"qc.reset({qubits[0]})"
    if name == "measure":
        if len(qubits) == 1 and len(clbits) == 1:
            return f"qc.measure({qubits[0]}, {clbits[0]})"
        report.add_warning("Measurement has invalid arity in Qiskit generator")
        return f"# Unsupported measure: {op}"

    # Single-Qubit Standard Gates
    if name == "id":
        return f"qc.id({qubits[0]})"
    if name == "x":
        return f"qc.x({qubits[0]})"
    if name == "y":
        return f"qc.y({qubits[0]})"
    if name == "z":
        return f"qc.z({qubits[0]})"
    if name == "h":
        return f"qc.h({qubits[0]})"
    if name == "s":
        return f"qc.s({qubits[0]})"
    if name == "sdg":
        return f"qc.sdg({qubits[0]})"
    if name == "t":
        return f"qc.t({qubits[0]})"
    if name == "tdg":
        return f"qc.tdg({qubits[0]})"
    if name == "sx":
        return f"qc.sx({qubits[0]})"
    if name == "sxdg":
        return f"qc.sxdg({qubits[0]})"
    if name in ("p", "phase"):
        return f"qc.p({params[0]}, {qubits[0]})"
    if name == "rx":
        return f"qc.rx({params[0]}, {qubits[0]})"
    if name == "ry":
        return f"qc.ry({params[0]}, {qubits[0]})"
    if name == "rz":
        return f"qc.rz({params[0]}, {qubits[0]})"
    if name == "u1":
        return f"qc.p({params[0]}, {qubits[0]})"
    if name == "u2":
        return f"qc.u(np.pi/2, {params[0]}, {params[1]}, {qubits[0]})"
    if name in ("u", "u3"):
        return f"qc.u({params[0]}, {params[1]}, {params[2]}, {qubits[0]})"

    # Two-Qubit / Controlled Gates
    if name in ("cx", "cnot"):
        return f"qc.cx({qubits[0]}, {qubits[1]})"
    if name == "cy":
        return f"qc.cy({qubits[0]}, {qubits[1]})"
    if name == "cz":
        return f"qc.cz({qubits[0]}, {qubits[1]})"
    if name == "ch":
        return f"qc.ch({qubits[0]}, {qubits[1]})"
    if name == "swap":
        return f"qc.swap({qubits[0]}, {qubits[1]})"
    if name == "cs":
        return f"qc.cs({qubits[0]}, {qubits[1]})"
    if name == "csdg":
        return f"qc.cp(-np.pi/2, {qubits[0]}, {qubits[1]})"
    if name == "ct":
        return f"qc.cp(np.pi/4, {qubits[0]}, {qubits[1]})"
    if name == "ctdg":
        return f"qc.cp(-np.pi/4, {qubits[0]}, {qubits[1]})"
    if name in ("cp", "cphase"):
        return f"qc.cp({params[0]}, {qubits[0]}, {qubits[1]})"
    if name == "crx":
        return f"qc.crx({params[0]}, {qubits[0]}, {qubits[1]})"
    if name == "cry":
        return f"qc.cry({params[0]}, {qubits[0]}, {qubits[1]})"
    if name == "crz":
        return f"qc.crz({params[0]}, {qubits[0]}, {qubits[1]})"
    if name == "cu1":
        return f"qc.cp({params[0]}, {qubits[0]}, {qubits[1]})"
    if name == "cu":
        return f"qc.cu({params[0]}, {params[1]}, {params[2]}, {params[3]}, {qubits[0]}, {qubits[1]})"
    if name == "cu3":
        return f"qc.cu({params[0]}, {params[1]}, {params[2]}, 0, {qubits[0]}, {qubits[1]})"

    # Multi-Qubit Gates
    if name in ("ccx", "toffoli"):
        return f"qc.ccx({qubits[0]}, {qubits[1]}, {qubits[2]})"
    if name == "cswap":
        return f"qc.cswap({qubits[0]}, {qubits[1]}, {qubits[2]})"
    if name in ("c3x", "c4x", "c5x"):
        controls = ", ".join(qubits[:-1])
        target = qubits[-1]
        return f"qc.mcx([{controls}], {target})"

    report.add_unsupported(f"Gate '{name}' not natively supported in Qiskit generator", op.line, op.col)
    return f"# Unsupported gate: {op}"
