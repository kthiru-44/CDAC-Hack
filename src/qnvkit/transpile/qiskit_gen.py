"""
Target Code Generator for Qiskit >= 1.0.0.

Emits runnable Python with modern Qiskit APIs: QuantumCircuit, if_test blocks and exact
parameters. Every gate of the IR has a native Qiskit form.
"""

from __future__ import annotations
from typing import Dict, List
from qnvkit.ir import CircuitIR, Condition, Op
from qnvkit.report import TranspilerReport, TranspileResult
from qnvkit.transpile._common import (
    py_name, fmt_param, qubit_names, clbit_names, set_metrics, condition_terms,
)

TARGET_VERSION = "qiskit>=1.0.0"

# name -> (qiskit method, template of parameters). {p0}.. are parameters; None = no parameters.
_SIMPLE = {
    "id": "id", "x": "x", "y": "y", "z": "z", "h": "h", "s": "s", "sdg": "sdg", "t": "t", "tdg": "tdg",
    "sx": "sx", "sxdg": "sxdg", "cx": "cx", "cy": "cy", "cz": "cz", "ch": "ch", "swap": "swap",
    "cs": "cs", "csdg": "csdg", "ccx": "ccx", "cswap": "cswap",
}
_ANGLE1 = {"p": "p", "u1": "p", "rx": "rx", "ry": "ry", "rz": "rz", "cp": "cp", "cu1": "cp",
           "crx": "crx", "cry": "cry", "crz": "crz"}
_FIXED_CP = {"ct": "np.pi/4", "ctdg": "-np.pi/4"}


def generate_qiskit_code(circuit: CircuitIR) -> TranspileResult:
    report = TranspilerReport(target="qiskit", target_version=TARGET_VERSION)
    set_metrics(report, circuit)
    qn, cn = qubit_names(circuit), clbit_names(circuit)
    ind = "    "

    lines = [
        '"""',
        "Generated by qnvkit OpenQASM 3.0 Transpiler",
        f"Target Framework: Qiskit ({TARGET_VERSION})",
        '"""',
        "import numpy as np",
        "from qiskit import QuantumCircuit, QuantumRegister, ClassicalRegister",
        "",
        "",
        "def build_circuit() -> QuantumCircuit:",
    ]
    regs = []
    for r in circuit.qregs:
        lines.append(f"{ind}{py_name(r.name)} = QuantumRegister({r.size}, name='{r.name}')")
        regs.append(py_name(r.name))
    for c in circuit.cregs:
        lines.append(f"{ind}{py_name(c.name)} = ClassicalRegister({c.size}, name='{c.name}')")
        regs.append(py_name(c.name))
    cname = py_name(circuit.name)
    lines.append(f"{ind}qc = QuantumCircuit({', '.join(regs)}, name='{circuit.name}')")
    lines.append("")

    for op in circuit.ops:
        code = _translate_op(op, qn, cn, report)
        if code is None:
            continue
        terms = condition_terms(circuit, op) if (op.condition and op.name != "barrier") else []
        if terms:
            cond = op.condition
            if isinstance(cond, Condition) and cond.index is not None:
                lines.append(f"{ind}with qc.if_test(({py_name(cond.register)}[{cond.index}], {cond.value})):")
            else:
                lines.append(f"{ind}with qc.if_test(({py_name(cond[0])}, {cond[1]})):")
            lines.append(f"{ind}{ind}{code}")
        else:
            lines.append(f"{ind}{code}")

    lines += [
        "",
        f"{ind}return qc",
        "",
        "",
        "if __name__ == '__main__':",
        "    circuit = build_circuit()",
        "    print('=== Generated Qiskit Circuit ===')",
        "    print(circuit.draw(output='text'))",
        "    try:",
        "        from qiskit.quantum_info import Statevector",
        "        sv = Statevector(circuit.remove_final_measurements(inplace=False))",
        "        print('\\nStatevector probabilities:')",
        "        print(sv.probabilities_dict())",
        "    except Exception as e:",
        "        print(f'Simulation note: {e}')",
    ]
    return TranspileResult(target="qiskit", code="\n".join(lines) + "\n", report=report)


def _translate_op(op: Op, qn: Dict[int, str], cn: Dict[int, str], report: TranspilerReport):
    name = op.name
    qs = [qn[q] for q in op.qubits]
    ps = [fmt_param(p) for p in op.params]
    if name == "barrier":
        return "qc.barrier(%s)" % ", ".join(qs)
    if name == "reset":
        return "qc.reset(%s)" % qs[0]
    if name == "measure":
        return "qc.measure(%s, %s)" % (qs[0], cn[op.clbits[0]])
    if name in _SIMPLE:
        return "qc.%s(%s)" % (_SIMPLE[name], ", ".join(qs))
    if name in _ANGLE1:
        return "qc.%s(%s)" % (_ANGLE1[name], ", ".join(ps + qs))
    if name in _FIXED_CP:
        return "qc.cp(%s, %s)" % (_FIXED_CP[name], ", ".join(qs))
    if name == "u2":
        return "qc.u(np.pi/2, %s, %s, %s)" % (ps[0], ps[1], qs[0])
    if name == "u3":
        return "qc.u(%s, %s, %s, %s)" % (ps[0], ps[1], ps[2], qs[0])
    if name == "cu3":
        return "qc.cu(%s, %s, %s, 0, %s, %s)" % (ps[0], ps[1], ps[2], qs[0], qs[1])
    if name == "cu2":
        return "qc.cu(np.pi/2, %s, %s, 0, %s, %s)" % (ps[0], ps[1], qs[0], qs[1])
    if name == "cu":
        return "qc.cu(%s, %s, %s, %s, %s, %s)" % (ps[0], ps[1], ps[2], ps[3], qs[0], qs[1])
    if name in ("c3x", "c4x", "c5x"):
        return "qc.mcx([%s], %s)" % (", ".join(qs[:-1]), qs[-1])
    report.add_unsupported(f"Gate '{name}' not supported by the Qiskit generator", op.line, op.col)
    return None
