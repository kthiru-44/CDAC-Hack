"""
Target Code Generator for C-DAC Qniverse QSDK.

Generates standalone, runnable Python code targeting the QSDK architecture:
QniverseCircuit, QuantumRegister, ClassicalRegister, and remote execution on
C-DAC PARAM / QACC supercomputing clusters.
"""

from __future__ import annotations
from typing import Tuple, Dict, Any
from qnvkit.ir import CircuitIR, Op
from qnvkit.report import TranspilerReport, TranspileResult

TARGET_VERSION = "QSDK (Qniverse 1.6+)"


def generate_qniverse_code(circuit: CircuitIR) -> TranspileResult:
    report = TranspilerReport(
        target="qniverse",
        target_version=TARGET_VERSION
    )

    lines = []
    lines.append('"""')
    lines.append(f'Generated by qnvkit OpenQASM 3.0 Transpiler')
    lines.append(f'Target Platform: C-DAC Qniverse QSDK ({TARGET_VERSION})')
    lines.append('"""')
    lines.append("import numpy as np")
    lines.append("try:")
    lines.append("    from Qniverse.QniverseCircuit import QniverseCircuit, QuantumRegister, ClassicalRegister")
    lines.append("    from Qniverse.gates import *")
    lines.append("    from Qniverse.backend import Backend")
    lines.append("    from Qniverse.api import run, fetch_job_result")
    lines.append("except ImportError:")
    lines.append("    # Fallback to qnvkit adapter shim if outside Qniverse JupyterLab")
    lines.append("    from qnvkit.qsdk_adapter import QniverseCircuit, QuantumRegister, ClassicalRegister\n")

    lines.append("def build_circuit() -> QniverseCircuit:")
    indent = "    "
    circuit_name = circuit.name.replace("-", "_")
    lines.append(f"{indent}qc = QniverseCircuit('{circuit_name}')\n")

    # 1. Register declarations
    for r in circuit.qregs:
        report.qubit_mapping[r.name] = r.size
        lines.append(f"{indent}{r.name} = QuantumRegister({r.size}, '{r.name}')")
        lines.append(f"{indent}qc.add_register({r.name})")

    for c in circuit.cregs:
        report.clbit_mapping[c.name] = c.size
        lines.append(f"{indent}{c.name} = ClassicalRegister({c.size}, '{c.name}')")
        lines.append(f"{indent}qc.add_register({c.name})")

    lines.append("")

    q_map = circuit.get_qubit_reg_map()
    c_map = circuit.get_clbit_reg_map()

    # 2. Operations
    gate_counts = {}
    for op in circuit.ops:
        gate_counts[op.name] = gate_counts.get(op.name, 0) + 1
        name = op.name.lower()

        qubits = []
        for q in op.qubits:
            if isinstance(q, int):
                r_name, r_idx = q_map.get(q, ('q', q))
                qubits.append(f"{r_name}[{r_idx}]")
            else:
                qubits.append(f"{q.register}[{q.index}]")

        clbits = []
        for cl in op.clbits:
            if isinstance(cl, int):
                cr_name, cr_idx = c_map.get(cl, ('c', cl))
                clbits.append(f"{cr_name}[{cr_idx}]")
            else:
                clbits.append(f"{cl.register}[{cl.index}]")

        params = [f"{p:.12g}" for p in op.params]

        if name == "barrier":
            lines.append(f"{indent}qc.add_gate('barrier', {', '.join(qubits)})")
        elif name == "reset":
            lines.append(f"{indent}qc.add_gate('reset', {qubits[0]})")
        elif name == "measure":
            if qubits and clbits:
                lines.append(f"{indent}qc.add_gate('measure', {qubits[0]}, {clbits[0]})")
        else:
            gate_expr = name
            if params:
                gate_expr = f"{name}({', '.join(params)})"

            q_args = ", ".join(qubits)
            if op.condition:
                if isinstance(op.condition, tuple):
                    cname, cval = op.condition
                    lines.append(f"{indent}qc.add_conditional_gate({cname}, {cval}, {gate_expr}, {q_args})")
                else:
                    c = op.condition
                    cond_reg = c.register
                    lines.append(f"{indent}qc.add_conditional_gate({cond_reg}, {c.value}, {gate_expr}, {q_args})")
            else:
                lines.append(f"{indent}qc.add_gate({gate_expr}, {q_args})")

    lines.append(f"\n{indent}return qc\n")

    # 3. Runnable __main__
    lines.append("if __name__ == '__main__':")
    lines.append("    circuit = build_circuit()")
    lines.append("    print('=== Generated QSDK Circuit ===')")
    lines.append("    print('OpenQASM 2.0 Export:')")
    lines.append("    print(circuit.qasm())")

    code_str = "\n".join(lines) + "\n"
    report.metrics = {
        "num_qubits": circuit.num_qubits,
        "num_clbits": circuit.num_clbits,
        "total_ops": len(circuit.ops),
        "gate_counts": gate_counts
    }

    return TranspileResult(target="qniverse", code=code_str, report=report)
