"""
Target Code Generator for NVIDIA CUDA-Q (tested with 0.16).

Inside ``@cudaq.kernel`` gates are bare names (``h(q[0])``, ``x.ctrl(c, t)``). Measurements are
``c_0 = mz(q[0])``; a kernel with measurements returns the classical bits as ``list[bool]`` (flat
order) so ``cudaq.run`` can read them, which is also what conditional feedback requires on
CUDA-Q >= 0.16.
"""

from __future__ import annotations
from typing import Dict, Set
from qnvkit.ir import CircuitIR, Op
from qnvkit.report import TranspilerReport, TranspileResult
from qnvkit.transpile._common import (
    prepare_ops, py_name, fmt_param, qubit_names, clbit_keys, set_metrics, condition_terms,
)

TARGET_VERSION = "cudaq>=0.9 (tested 0.16)"

NATIVE = {
    "id", "x", "y", "z", "h", "s", "sdg", "t", "tdg", "p", "u1", "u2", "u3", "rx", "ry", "rz",
    "cx", "cy", "cz", "ch", "swap", "cs", "csdg", "ct", "ctdg", "cp", "cu1", "crx", "cry", "crz",
    "cu2", "cu3", "ccx", "cswap", "c3x", "c4x", "c5x",
}


def generate_cudaq_code(circuit: CircuitIR) -> TranspileResult:
    if not isinstance(circuit, CircuitIR):
        # also accept a QniverseCircuit (read through qc.qasm())
        from qnvkit.qsdk_adapter import from_qniverse
        circuit = from_qniverse(circuit)
    report = TranspilerReport(target="cudaq", target_version=TARGET_VERSION)
    set_metrics(report, circuit)
    qn = qubit_names(circuit)
    keys = clbit_keys(circuit)
    ops = prepare_ops(circuit, NATIVE, {"u3", "cx"}, report, "CUDA-Q")
    ind = "    "

    has_measure = any(o.name == "measure" for o in ops)
    kname = py_name(circuit.name)
    body = []
    measured: Set[int] = set()
    for op in ops:
        if op.name == "barrier":
            report.add_note("barrier omitted: CUDA-Q kernels have no barrier operation")
            continue
        if op.name == "measure" and op.condition:
            report.add_unsupported("Conditional measurement is not supported by the CUDA-Q generator", op.line, op.col)
            continue
        stmts = _translate(op, qn, keys, report)
        if not stmts:
            continue
        pad = ind
        if op.condition:
            tests = []
            never = False
            for bit, req in condition_terms(circuit, op):
                if bit in measured:
                    tests.append(keys[bit] if req else f"not {keys[bit]}")
                elif req == 1:
                    never = True
            if never:
                report.add_warning("Condition can never hold (bit tested for 1 before any measurement); operation skipped")
                continue
            for t in tests:
                body.append(f"{pad}if {t}:")
                pad += ind
        for s in stmts:
            body.append(pad + s)
        if op.name == "measure":
            measured.add(op.clbits[0])
            body.append(f"{ind}result_bits[{op.clbits[0]}] = {keys[op.clbits[0]]}")

    lines = [
        '"""',
        "Generated by qnvkit OpenQASM 3.0 Transpiler",
        f"Target Framework: NVIDIA CUDA-Q ({TARGET_VERSION})",
        '"""',
        "import numpy as np",
        "import cudaq",
        "",
        "",
        "@cudaq.kernel",
        f"def {kname}()" + (" -> list[bool]:" if has_measure else ":"),
    ]
    for r in circuit.qregs:
        lines.append(f"{ind}{py_name(r.name)} = cudaq.qvector({r.size})")
    if has_measure:
        lines.append(f"{ind}result_bits = [{', '.join(['False'] * circuit.num_clbits)}]")
    if not circuit.qregs:
        lines.append(f"{ind}pass")
    lines.extend(body)
    if has_measure:
        lines.append(f"{ind}return result_bits")
    lines += ["", "", f"KERNEL = {kname}", f"NUM_CLBITS = {circuit.num_clbits}", "SHOTS = 1024", "", "",
              "if __name__ == '__main__':"]
    if has_measure:
        lines += [
            "    shots = cudaq.run(KERNEL, shots_count=SHOTS)",
            "    counts = {}",
            "    for bits in shots:",
            "        # classical bit 0 right-most",
            "        s = ''.join('1' if b else '0' for b in reversed(list(bits)))",
            "        counts[s] = counts.get(s, 0) + 1",
            "    print(f'Counts ({SHOTS} shots, classical bit 0 right-most):')",
            "    print(dict(sorted(counts.items())))",
        ]
    else:
        lines += [
            "    state = cudaq.get_state(KERNEL)",
            "    print('State vector (CUDA-Q index order):')",
            "    print(np.round(np.array(state), 4))",
        ]
    return TranspileResult(target="cudaq", code="\n".join(lines) + "\n", report=report)


def _translate(op: Op, qn: Dict[int, str], keys: Dict[int, str], report: TranspilerReport):
    name = op.name
    qs = [qn[q] for q in op.qubits]
    ps = [fmt_param(p) for p in op.params]
    a = ", ".join(qs)
    if name == "id":
        return []
    if name == "reset":
        return [f"reset({qs[0]})"]
    if name == "measure":
        return [f"{keys[op.clbits[0]]} = mz({qs[0]})"]
    if name in ("x", "y", "z", "h", "s", "t"):
        return [f"{name}({a})"]
    if name in ("sdg", "tdg"):
        return [f"{name[0]}.adj({a})"]
    if name in ("rx", "ry", "rz"):
        return [f"{name}({ps[0]}, {a})"]
    if name in ("p", "u1"):
        return [f"r1({ps[0]}, {a})"]
    if name == "u3":
        return [f"u3({ps[0]}, {ps[1]}, {ps[2]}, {a})"]
    if name == "u2":
        return [f"u3(1.5707963267948966, {ps[0]}, {ps[1]}, {a})"]
    if name == "swap":
        return [f"swap({a})"]
    if name == "cx":
        return [f"x.ctrl({a})"]
    if name in ("cy", "cz", "ch", "cs", "ct"):
        return [f"{name[1]}.ctrl({a})"]
    if name == "csdg":
        return [f"r1.ctrl(-1.5707963267948966, {a})"]
    if name == "ctdg":
        return [f"r1.ctrl(-0.7853981633974483, {a})"]
    if name in ("cp", "cu1"):
        return [f"r1.ctrl({ps[0]}, {a})"]
    if name in ("crx", "cry", "crz"):
        return [f"{name[1:]}.ctrl({ps[0]}, {a})"]
    if name == "cu3":
        return [f"u3.ctrl({ps[0]}, {ps[1]}, {ps[2]}, {a})"]
    if name == "cu2":
        return [f"u3.ctrl(1.5707963267948966, {ps[0]}, {ps[1]}, {a})"]
    if name == "cswap":
        return [f"swap.ctrl({a})"]
    if name in ("ccx", "c3x", "c4x", "c5x"):
        return [f"x.ctrl([{', '.join(qs[:-1])}], {qs[-1]})"]
    report.add_unsupported(f"Gate '{name}' not supported by the CUDA-Q generator", op.line, op.col)
    return []
